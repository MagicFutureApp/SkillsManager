// Generates apps/desktop/src/generated/build-env.ts from build-time environment
// variables. This is the single injection point for secrets/endpoints that the
// packaged desktop app must carry, mirroring how the landing release step reads
// CLOUDFLARE_API_TOKEN from the environment.
//
// Required env vars (no hardcoded defaults — the build fails if either is missing):
//   SKILLS_MANAGER_CACHE_SYNC_TOKEN  token authenticating the desktop against the
//                                     cache-manager Worker's read/sync endpoints
//   BEST_100_DEFAULT_API_BASE        default Worker API base URL baked into the app
//
// Where the values come from:
//   - Local dev:     process.env, or apps/desktop/.env (gitignored, copied from
//                    .env.example). The shell env wins over .env.
//   - Production CI: GitHub Actions secrets of the same names, exported into the
//                    "Build installer" step (see .github/workflows/build-desktop-installers.yml).
//
// If a value is absent, the script prints an error and exits non-zero so the build
// aborts loudly instead of baking a missing/placeholder secret into the app.

import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const desktopRoot = resolve(scriptDir, "..");

/**
 * Load a local, gitignored .env if present and merge it into process.env.
 * Shell environment variables take precedence over .env values.
 */
function loadLocalEnv() {
  const envPath = resolve(desktopRoot, ".env");

  if (!existsSync(envPath)) {
    return;
  }

  try {
    const text = readFileSync(envPath, "utf8");

    for (const rawLine of text.split(/\r?\n/)) {
      const line = rawLine.trim();

      if (!line || line.startsWith("#")) {
        continue;
      }

      const eq = line.indexOf("=");

      if (eq === -1) {
        continue;
      }

      const key = line.slice(0, eq).trim();
      let value = line.slice(eq + 1).trim();

      if (
        (value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))
      ) {
        value = value.slice(1, -1);
      }

      if (process.env[key] === undefined) {
        process.env[key] = value;
      }
    }
  } catch {
    // Ignore unreadable .env; the required-value check below will surface any gap.
  }
}

loadLocalEnv();

/** Read a required build var, exiting non-zero if it is missing or empty. */
function requireBuildVar(name) {
  const value = process.env[name];

  if (value && value.trim() !== "") {
    return value.trim();
  }

  console.error(
    `[generate-build-env] Missing required build variable "${name}".\n` +
      "  - For local dev, set it in apps/desktop/.env (copy .env.example and fill it in).\n" +
      "  - For CI/production, configure it as a GitHub Actions secret with the same name.\n" +
      "Build aborted."
  );
  process.exit(1);
}

const syncToken = requireBuildVar("SKILLS_MANAGER_CACHE_SYNC_TOKEN");
const apiBase = requireBuildVar("BEST_100_DEFAULT_API_BASE");

const target = resolve(desktopRoot, "src/generated/build-env.ts");
mkdirSync(dirname(target), { recursive: true });

const content = `// AUTO-GENERATED by scripts/generate-build-env.mjs — do not edit by hand.
// Values are injected at build time from required environment variables:
//   SKILLS_MANAGER_CACHE_SYNC_TOKEN  (Worker read/sync auth token)
//   BEST_100_DEFAULT_API_BASE        (default Worker API base URL)
// There are no dev fallbacks; a missing value aborts the build.

export const BUILD_ENV = {
  best100SyncToken: ${JSON.stringify(syncToken)},
  best100ApiBase: ${JSON.stringify(apiBase)}
} as const;
`;

writeFileSync(target, content, "utf8");

console.log(`[generate-build-env] wrote ${target}`);
console.log(
  `[generate-build-env] syncToken=${syncToken ? "<set>" : "<empty>"} apiBase=${apiBase}`
);
