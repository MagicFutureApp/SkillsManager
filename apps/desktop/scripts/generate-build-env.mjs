// Generates apps/desktop/src/generated/build-env.ts from build-time environment
// variables. This is the single injection point for secrets/endpoints that the
// packaged desktop app must carry, mirroring how the landing release step reads
// CLOUDFLARE_API_TOKEN from the environment.
//
// Env vars (highest priority first):
//   SKILLS_MANAGER_CACHE_SYNC_TOKEN  token authenticating the desktop against the
//                                     cache-manager Worker's read/sync endpoints
//   BEST_100_DEFAULT_API_BASE        default Worker API base URL baked into the app
//
// Precedence for each value: process.env  >  local .env (gitignored)  > dev fallback.
// Dev fallbacks keep `pnpm dev` working with zero setup; CI builds MUST set the
// real env vars so production bundles never ship the dev defaults.

import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const desktopRoot = resolve(scriptDir, "..");

// Dev fallbacks — must match apps/cache-manager/.dev.vars for `pnpm dev:test`.
const DEV_SYNC_TOKEN = "gmsP0i8iXCTunM0zoiHR8mPG8U6Bt8mefYkTHPeQp1U";
const DEV_API_BASE = "http://localhost:8787";

/** Load a local, gitignored .env if present (no third-party dependency needed). */
function loadLocalEnv() {
  const envPath = resolve(desktopRoot, ".env");
  const out = {};

  if (!existsSync(envPath)) {
    return out;
  }

  try {
    const text = readFileSync(envPath, "utf8");

    for (const rawLine of text.split(/\r?\n/)) {
      const line = rawLine.trim();

      if (!line || line.startsWith("#")) {
        continue;
      }

      const eq = line.indexOf("=");

      if (eq === -1) {
        continue;
      }

      const key = line.slice(0, eq).trim();
      let value = line.slice(eq + 1).trim();

      if (
        (value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))
      ) {
        value = value.slice(1, -1);
      }

      out[key] = value;
    }
  } catch {
    // Ignore unreadable .env; dev fallback applies.
  }

  return out;
}

const localEnv = loadLocalEnv();

const syncToken =
  process.env.SKILLS_MANAGER_CACHE_SYNC_TOKEN ||
  localEnv.SKILLS_MANAGER_CACHE_SYNC_TOKEN ||
  DEV_SYNC_TOKEN;

const apiBase =
  process.env.BEST_100_DEFAULT_API_BASE ||
  localEnv.BEST_100_DEFAULT_API_BASE ||
  DEV_API_BASE;

if (
  !process.env.SKILLS_MANAGER_CACHE_SYNC_TOKEN &&
  !localEnv.SKILLS_MANAGER_CACHE_SYNC_TOKEN
) {
  console.warn(
    "[generate-build-env] SKILLS_MANAGER_CACHE_SYNC_TOKEN not set — using DEV fallback token (do not ship to production)."
  );
}

if (
  !process.env.BEST_100_DEFAULT_API_BASE &&
  !localEnv.BEST_100_DEFAULT_API_BASE
) {
  console.warn(
    "[generate-build-env] BEST_100_DEFAULT_API_BASE not set — using DEV fallback base (http://localhost:8787)."
  );
}

const target = resolve(desktopRoot, "src/generated/build-env.ts");
mkdirSync(dirname(target), { recursive: true });

const content = `// AUTO-GENERATED by scripts/generate-build-env.mjs — do not edit by hand.
// Values are injected at build time from environment variables:
//   SKILLS_MANAGER_CACHE_SYNC_TOKEN  (Worker read/sync auth token)
//   BEST_100_DEFAULT_API_BASE        (default Worker API base URL)
// Dev fallback values are used when those env vars are absent (see the generator script).

export const BUILD_ENV = {
  best100SyncToken: ${JSON.stringify(syncToken)},
  best100ApiBase: ${JSON.stringify(apiBase)}
} as const;
`;

writeFileSync(target, content, "utf8");

console.log(`[generate-build-env] wrote ${target}`);
console.log(
  `[generate-build-env] syncToken=${syncToken ? "<set>" : "<empty>"} apiBase=${apiBase}`
);
